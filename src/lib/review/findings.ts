/**
 * What the model returns is untrusted. Everything is checked here before anything is
 * posted to GitHub: the file must be in the pull request, the line must be in the diff,
 * and the text is cleaned so it cannot ping people or load images.
 */

export const SEVERITIES = ["Security", "Potential Bug", "Performance", "Maintainability"] as const;
export type Severity = (typeof SEVERITIES)[number];

export const MAX_COMMENTS = 8;

export interface Finding {
  path: string;
  line: number;
  severity: Severity;
  title: string;
  explanation: string;
  suggestion: string | null;
  confidence: "high" | "medium";
}

export interface FileLines {
  rightLines: ReadonlySet<number>;
  addedLines: ReadonlySet<number>;
}

const DANGEROUS_TAGS =
  /<\/?(img|script|iframe|a|style|svg|form|input|link|meta|object|embed|video|audio|source|base|button|textarea|details|summary)\b[^>]*>/gi;

/** Removes images and risky HTML, stops @mentions from notifying anyone, and blocks fake suggestion blocks. */
export function sanitizeText(value: string, max: number): string {
  return value
    .replace(/\r\n/g, "\n")
    .replace(/!\[[^\]]*\]\([^)]*\)/g, "")
    .replace(DANGEROUS_TAGS, "")
    .replace(/@(?=[A-Za-z0-9_-])/g, "@\u200b")
    .replace(/```\s*suggestion/gi, "```text")
    .trim()
    .slice(0, max);
}

const isRecord = (value: unknown): value is Record<string, unknown> =>
  typeof value === "object" && value !== null && !Array.isArray(value);

const SEVERITY_RANK: Record<Severity, number> = { Security: 0, "Potential Bug": 1, Performance: 2, Maintainability: 3 };

export function validateFindings(raw: unknown, files: ReadonlyMap<string, FileLines>, max = MAX_COMMENTS): Finding[] {
  const list = Array.isArray(raw) ? raw : isRecord(raw) && Array.isArray(raw.findings) ? raw.findings : [];
  const seen = new Set<string>();
  const valid: Finding[] = [];

  for (const item of list) {
    if (!isRecord(item)) continue;

    const path = typeof item.path === "string" ? item.path : "";
    const lines = files.get(path);
    if (!lines) continue; // not a file in this pull request

    const line = item.line;
    if (typeof line !== "number" || !Number.isInteger(line) || !lines.rightLines.has(line)) continue; // not a line in the diff

    const severity = item.severity;
    if (!SEVERITIES.includes(severity as Severity)) continue;
    const confidence = item.confidence;
    if (confidence !== "high" && confidence !== "medium") continue; // "low" is dropped on purpose

    const title = sanitizeText(typeof item.title === "string" ? item.title : "", 120);
    const explanation = sanitizeText(typeof item.explanation === "string" ? item.explanation : "", 1200);
    if (!title || !explanation) continue;

    const key = `${path}:${line}`;
    if (seen.has(key)) continue;
    seen.add(key);

    // A one-click suggestion is only offered for added lines, and only if it cannot break out of its code block.
    let suggestion: string | null = null;
    const rawSuggestion = typeof item.suggestion === "string" ? item.suggestion.replace(/\r\n/g, "\n") : "";
    if (
      rawSuggestion.trim() !== "" &&
      lines.addedLines.has(line) &&
      !rawSuggestion.includes("```") &&
      rawSuggestion.length <= 1500 &&
      rawSuggestion.split("\n").length <= 15
    ) {
      suggestion = rawSuggestion.replace(/\n+$/, "");
    }

    valid.push({ path, line, severity: severity as Severity, title, explanation, suggestion, confidence });
  }

  valid.sort(
    (a, b) =>
      SEVERITY_RANK[a.severity] - SEVERITY_RANK[b.severity] ||
      Number(b.confidence === "high") - Number(a.confidence === "high"),
  );
  return valid.slice(0, max);
}

/** The text of one inline comment. */
export function formatCommentBody(finding: Finding): string {
  const parts = [`**${finding.severity}: ${finding.title}**`, "", finding.explanation];
  if (finding.suggestion) parts.push("", "```suggestion", finding.suggestion, "```");
  parts.push("", "<sub>Generated by RepoMind AI. A suggestion to verify, not a confirmed issue.</sub>");
  return parts.join("\n");
}

/** The text at the top of the whole review. */
export function buildSummary(input: { findings: Finding[]; reviewedFiles: number; skippedFiles: number; usedContext: boolean }): string {
  const { findings, reviewedFiles, skippedFiles, usedContext } = input;

  const counts = SEVERITIES.map((s) => [s, findings.filter((f) => f.severity === s).length] as const).filter(([, n]) => n > 0);
  const headline =
    findings.length === 0
      ? "No clear issues found in the changes I reviewed."
      : `Found ${findings.length} potential ${findings.length === 1 ? "issue" : "issues"}: ${counts.map(([s, n]) => `${n} ${s}`).join(", ")}.`;

  const notes = [`Reviewed ${reviewedFiles} changed ${reviewedFiles === 1 ? "file" : "files"}.`];
  if (skippedFiles > 0) notes.push(`${skippedFiles} ${skippedFiles === 1 ? "file was" : "files were"} not reviewed (lockfiles, generated or very large diffs, or files that may contain secrets).`);
  if (!usedContext) notes.push("This review used the diff only. Index the repository in RepoMind AI so reviews can use related code from elsewhere in the project.");

  return [
    "### RepoMind AI review",
    "",
    headline,
    "",
    notes.join(" "),
    "",
    "<sub>AI-generated suggestions for you to verify. They are not confirmed vulnerabilities, and a review with no findings does not mean the code is safe.</sub>",
  ].join("\n");
}

/** Reads findings back from the database defensively. */
export function parseStoredFindings(value: unknown): Finding[] {
  if (!Array.isArray(value)) return [];
  return value.filter(
    (f): f is Finding =>
      isRecord(f) &&
      typeof f.path === "string" &&
      typeof f.line === "number" &&
      typeof f.title === "string" &&
      typeof f.explanation === "string" &&
      SEVERITIES.includes(f.severity as Severity),
  );
}